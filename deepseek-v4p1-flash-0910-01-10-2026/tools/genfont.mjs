const FIRST = 32;
const LAST = 95;
const lines = [];
lines.push('; ── FONT ── 64 glyphs, 5x7, one 5-bit word per row (ASCII 32–95) ──');
for (let code = FIRST; code <= LAST; code++) {
  const ch = String.fromCharCode(code);
  const glyph = GLYPHS[ch];
  if (!glyph) {
    console.error(`missing glyph for ${code} '${ch}'`);
    process.exit(1);
  }
  const rows = glyph.trim().split('\n');
  if (rows.length !== 7 || rows.some((r) => r.length !== 5)) {
    console.error(`glyph '${ch}' is not 7x5`);
    process.exit(1);
  }
  const values = rows.map((r) => '0b' + [...r].map((c) => (c === '#' ? '1' : '0')).join(''));
  const label = ch === "'" ? 'quote' : ch === '\\' ? 'backslash' : ch;
  lines.push(`    .word ${values.join(', ')}  ; '${label}' (${code})`);
}
const body = lines.join('\n');
const out = `/* Generated by tools/genfont.mjs — do not edit by hand. */
export const FONT_ASM = ${JSON.stringify(body)};
`;
writeFileSync(new URL('../js/font.inc.js', import.meta.url), out);
console.log(`wrote js/font.inc.js (${LAST - FIRST + 1} glyphs, ${(LAST - FIRST + 1) * 7} words)`);
